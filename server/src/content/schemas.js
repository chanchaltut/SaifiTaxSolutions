// ─────────────────────────────────────────────────────────────
// THE single description of everything the admin can edit.
//
// From this one file the server builds the database models, checks
// every save, and sends the admin panel the forms to draw. A field
// added here appears in the panel, is validated and stored, and is
// sent to the website with no other server change. Labels and help
// text are written for the firm's staff, not for programmers.
//
// Field types
//   text, textarea, longtext (paragraphs), richtext (article editor),
//   number, boolean, datetime, select, combo (pick or type), link
//   (site page or web address), url, email, image, file (an uploaded
//   PDF), list, slug, heading (a sub-title in long forms; stores nothing)
//
// Common options
//   required, help, placeholder, max (characters / value), min, options,
//   source (options loaded from the content, e.g. every service name),
//   aspect (image shape), when (only show when another field has a
//   value), half (half-width), advanced (inside "More options"),
//   internal (kept and checked, never shown: built-in ids the site uses)
// ─────────────────────────────────────────────────────────────

